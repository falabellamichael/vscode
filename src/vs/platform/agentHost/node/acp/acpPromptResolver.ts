import { URI } from '../../../../base/common/uri.js';
import { localize } from '../../../../nls.js';
import { isAgentFeedbackAnnotationsAttachment, renderAgentFeedbackAnnotationsAttachment } from '../../common/meta/agentFeedbackAttachments.js';
import { isHostSnapshotAttachment } from '../../common/meta/agentSnapshotAttachmentMeta.js';
import { MessageAttachmentKind, type MessageAttachment } from '../../common/state/sessionState.js';

export interface IAcpPromptCapabilities {
	readonly image?: boolean;
	readonly embeddedContext?: boolean;
}

/** Preserve host context without requiring the agent to read editor-only resources. */
export function resolveAcpPrompt(prompt: string, attachments: readonly MessageAttachment[] | undefined, capabilities: IAcpPromptCapabilities): Record<string, unknown>[] {
	const blocks: Record<string, unknown>[] = [{ type: 'text', text: prompt }];
	for (const attachment of attachments ?? []) {
		if (isAgentFeedbackAnnotationsAttachment(attachment)) {
			const text = renderAgentFeedbackAnnotationsAttachment(attachment);
			if (text) { blocks.push({ type: 'text', text }); }
			continue;
		}
		switch (attachment.type) {
			case MessageAttachmentKind.Simple:
				// Provider completions may be display-only and have no model representation.
				if (attachment.modelRepresentation) { blocks.push({ type: 'text', text: attachment.modelRepresentation }); }
				break;
			case MessageAttachmentKind.Resource: {
				const uri = URI.parse(attachment.uri);
				const range = attachment.selection?.range;
				const endLine = range && range.end.character === 0 && range.end.line > range.start.line ? range.end.line - 1 : range?.end.line;
				const selection = range ? ` (lines ${range.start.line + 1}-${endLine! + 1})` : '';
				const snapshot = isHostSnapshotAttachment(attachment) ? ' (read-only snapshot; do not edit this file)' : '';
				blocks.push({ type: 'resource_link', uri: uri.toString(), name: attachment.label, ...(attachment.contentType ? { mimeType: attachment.contentType } : {}) });
				blocks.push({ type: 'text', text: `${attachment.label}: ${uri.scheme === 'file' ? uri.fsPath : uri.toString()}${selection}${snapshot}` });
				break;
			}
			case MessageAttachmentKind.EmbeddedResource: {
				const mimeType = attachment.contentType.toLowerCase().split(';', 1)[0].trim();
				const textual = mimeType.startsWith('text/') || ['application/json', 'application/xml', 'application/javascript', 'application/typescript'].includes(mimeType) || mimeType.endsWith('+json') || mimeType.endsWith('+xml');
				if (textual) {
					const range = attachment.selection?.range;
					const selection = range ? ` (selection starts at line ${range.start.line + 1})` : '';
					blocks.push({ type: 'text', text: `${attachment.label}${selection} (read-only attached content):\n${Buffer.from(attachment.data, 'base64').toString('utf8')}` });
				} else if (mimeType.startsWith('image/') && capabilities.image) {
					blocks.push({ type: 'image', mimeType: attachment.contentType, data: attachment.data });
				} else if (capabilities.embeddedContext && !mimeType.startsWith('image/')) {
					blocks.push({ type: 'resource', resource: { uri: URI.from({ scheme: 'attachment', path: `/${encodeURIComponent(attachment.label)}` }).toString(), mimeType: attachment.contentType, blob: attachment.data } });
				} else {
					throw new Error(localize('devin.unsupportedAttachment', "Devin did not advertise support for the attachment \"{0}\" ({1}). Remove it or attach text instead.", attachment.label, attachment.contentType));
				}
				break;
			}
			default:
				throw new Error(localize('devin.unresolvedAttachment', "The attachment \"{0}\" could not be resolved to context for Devin.", attachment.label));
		}
	}
	return blocks;
}
